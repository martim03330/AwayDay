// Generates supabase/seed/*.sql from the catalogue bundled in src/features/fixtures/snapshot.ts.
// Usage: npm run db:seed. First time: `supabase db push --include-seed`. After that, push only records
// the new file hash, so apply changed files with `supabase db query --linked -f supabase/seed/<file>.sql`.
// Every statement is an upsert by id, so running the seed again is safe.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { bundledCatalogRows } from '../src/features/fixtures/snapshot.ts';

const seedDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'seed');
const header = '-- Generated by scripts/generate-fixtures-seed.mjs from src/features/fixtures/snapshot.ts.\n-- Do not edit by hand: change the snapshot and run `npm run db:seed`.\n\n';

function literal(value) {
  if (value === null) return 'null';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error(`Invalid number: ${value}`);
    return String(value);
  }
  if (typeof value === 'string') return `'${value.replaceAll("'", "''")}'`;
  throw new Error(`Unsupported value: ${JSON.stringify(value)}`);
}

function point(latitude, longitude) {
  if (latitude === null || longitude === null) return 'null';
  return `extensions.st_setsrid(extensions.st_makepoint(${literal(longitude)}, ${literal(latitude)}), 4326)::extensions.geography`;
}

function upsert(table, columns, rows, toValues) {
  const values = rows.map((row) => `  (${toValues(row).join(', ')})`).join(',\n');
  const updates = columns
    .filter((column) => column !== 'id')
    .map((column) => `${column} = excluded.${column}`)
    .join(',\n  ');
  return `${header}insert into public.${table} (${columns.join(', ')})\nvalues\n${values}\non conflict (id) do update set\n  ${updates};\n`;
}

const { competitions, venues, clubs, fixtures } = bundledCatalogRows;
const files = {
  '01_competitions.sql': upsert('competition', ['id', 'name', 'kind', 'tier'], competitions, (row) =>
    [row.id, row.name, row.kind, row.tier].map(literal)
  ),
  '02_venues.sql': upsert(
    'venue',
    ['id', 'name', 'city', 'country', 'region', 'capacity', 'location', 'roof_coverage', 'address'],
    venues,
    (row) => [
      ...[row.id, row.name, row.city, row.country, row.region, row.capacity].map(literal),
      point(row.latitude, row.longitude),
      literal(row.roof_coverage),
      literal(row.address),
    ]
  ),
  '03_clubs.sql': upsert(
    'club',
    ['id', 'name', 'short_name', 'abbreviation', 'country', 'primary_color', 'secondary_color', 'tier', 'home_venue_id'],
    clubs,
    (row) =>
      [row.id, row.name, row.short_name, row.abbreviation, row.country, row.primary_color, row.secondary_color, row.tier, row.home_venue_id].map(literal)
  ),
  '04_fixtures.sql': upsert(
    'fixture',
    ['id', 'competition_id', 'stage', 'home_club_id', 'away_club_id', 'venue_id', 'kickoff_at'],
    fixtures,
    (row) =>
      [row.id, row.competition_id, row.stage, row.home_club_id, row.away_club_id, row.venue_id, row.kickoff_at].map(literal)
  ),
};

mkdirSync(seedDir, { recursive: true });
for (const [name, sql] of Object.entries(files)) writeFileSync(join(seedDir, name), sql);
console.log(`Seed written: ${competitions.length} competitions, ${venues.length} venues, ${clubs.length} clubs, ${fixtures.length} fixtures.`);
