// Imports the research on home fans (JSON files, one per group of stadiums) into public.venue_safety_note, for visiting
// fans at every stadium. Every note keeps its sources. Only high and medium confidence items are imported.
//
// - areas -> zona_adeptos_casa (stands, gates or streets home supporters hold; text, no map area unless known);
// - places -> zona_adeptos_casa (a named premises used by home supporters);
// - away_route_pt -> percurso_visitantes (the official route or entrance for visiting fans).
// Re-running replaces the imported notes of those stadiums (ids start with "casa-" and "percurso-").
//
// Usage:
//   npm run --silent db:adeptos-casa -- <file.json> [more.json...] > /tmp/adeptos-casa.sql   (report on stderr)
//   supabase db query --linked -f /tmp/adeptos-casa.sql
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';

const files = process.argv.slice(2);
if (files.length === 0) {
  console.error(
    'Uso: npm run --silent db:adeptos-casa -- <ficheiro.json> [...] > adeptos-casa.sql'
  );
  process.exit(1);
}

const TODAY = new Date().toISOString().slice(0, 10);

function literal(value) {
  if (value === null || value === undefined) return 'null';
  return `'${String(value).replaceAll("'", "''")}'`;
}

function clip(text, max) {
  const value = typeof text === 'string' ? text.trim() : '';
  if (!value) return null;
  return value.length <= max ? value : `${value.slice(0, max - 1).trimEnd()}…`;
}

/** Sources in the shape venue_safety_note uses: [{ title, url, date }]. */
function cleanSources(sources) {
  return (Array.isArray(sources) ? sources : [])
    .filter((source) => typeof source?.url === 'string' && source.url.startsWith('https://'))
    .map((source) => ({
      title: String(source.title ?? '').slice(0, 160) || source.url,
      url: source.url,
      date: /^\d{4}-\d{2}-\d{2}$/.test(source.published ?? '') ? source.published : null,
    }));
}

/** The most recent full date among the sources, or today when none has one. */
function referenceDate(sources) {
  const dates = sources
    .map((source) => source.date)
    .filter(Boolean)
    .sort();
  return dates[dates.length - 1] ?? TODAY;
}

function noteId(prefix, venueId, title) {
  return `${prefix}-${venueId}-${createHash('md5').update(title).digest('hex').slice(0, 8)}`;
}

const statements = [];
const report = { notes: 0, skipped: [] };

for (const file of files) {
  for (const group of JSON.parse(await readFile(file, 'utf8'))) {
    const venueId = group.venue_id;
    statements.push(
      `delete from public.venue_safety_note where venue_id = ${literal(venueId)} and (id like 'casa-%' or id like 'percurso-%');`
    );

    const items = [
      ...(group.areas ?? []).map((area) => ({
        title: area.name,
        text: area.advice_pt,
        sources: area.sources,
        confidence: area.confidence,
      })),
      ...(group.places ?? []).map((place) => ({
        title: place.name,
        text: place.why_pt,
        sources: place.sources,
        confidence: place.confidence,
      })),
    ];
    for (const item of items) {
      const sources = cleanSources(item.sources);
      const title = clip(item.title, 120);
      const description = clip(item.text, 600);
      if (item.confidence !== 'high' && item.confidence !== 'medium') {
        report.skipped.push(`${venueId} · ${item.title}: confiança baixa`);
        continue;
      }
      if (!title || !description || sources.length === 0) {
        report.skipped.push(`${venueId} · ${item.title}: sem texto ou fontes`);
        continue;
      }
      statements.push(
        `insert into public.venue_safety_note (id, venue_id, visiting_club_id, kind, title, description, reference_date, sources) values (` +
          `${literal(noteId('casa', venueId, title))}, ${literal(venueId)}, null, 'zona_adeptos_casa', ${literal(title)}, ${literal(description)}, ` +
          `${literal(referenceDate(sources))}, ${literal(JSON.stringify(sources))}::jsonb) on conflict (id) do nothing;`
      );
      report.notes += 1;
    }

    const routeSources = cleanSources(group.away_route_sources);
    const route = clip(group.away_route_pt, 600);
    if (route && routeSources.length > 0) {
      statements.push(
        `insert into public.venue_safety_note (id, venue_id, visiting_club_id, kind, title, description, reference_date, sources) values (` +
          `${literal(noteId('percurso', venueId, route))}, ${literal(venueId)}, null, 'percurso_visitantes', 'Percurso e entrada dos visitantes', ${literal(route)}, ` +
          `${literal(referenceDate(routeSources))}, ${literal(JSON.stringify(routeSources))}::jsonb) on conflict (id) do nothing;`
      );
      report.notes += 1;
    }
  }
}

console.log('-- Generated by scripts/importar-adeptos-casa.mjs from the home fans research.');
console.log('begin;');
console.log(statements.join('\n'));
console.log('commit;');
console.error(`${report.notes} notas; ${report.skipped.length} de fora:`);
for (const line of report.skipped) console.error(`  - ${line}`);
