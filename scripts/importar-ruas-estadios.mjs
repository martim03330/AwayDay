// Imports the named streets around each stadium from OpenStreetMap into public.venue_street.
//
// They are the canvas for "as ruas onde costumam estar os adeptos da casa": what the fans flag is a ~150 m cell, and
// a cell on its own means nothing to anyone. Snapped to the street it sits on, it becomes something a visiting fan
// can actually use ("nesta rua costuma estar gente da casa").
//
// What comes in: ways with a name that people walk or drive on, within 1,5 km of the stadium. Motorway slip roads,
// tracks and paths without a name are left out: nobody says "estavam na via rápida".
//
// Usage:
//   npm run --silent db:ruas -- [venue-id ...] > /tmp/ruas.sql   (report on stderr)
//   supabase db query --linked -f /tmp/ruas.sql
//
// Data: © OpenStreetMap contributors (Overpass). This runs on a developer machine.

const OVERPASS = 'https://maps.mail.ru/osm/tools/overpass/api/interpreter';
const USER_AGENT = 'AwayDay/0.1 (stadium streets import; developer machine)';

const RADIUS_M = 1500;
/** Streets people are actually on, on foot or by car. */
const HIGHWAYS =
  '^(primary|secondary|tertiary|residential|unclassified|pedestrian|living_street|footway|path)$';
/** A street is kept as one line per OSM way; ways shorter than this are noise. */
const MIN_POINTS = 2;

const SUPABASE_URL = process.env.EXPO_PUBLIC_SUPABASE_URL;
const SUPABASE_KEY = process.env.EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
if (!SUPABASE_URL || !SUPABASE_KEY) {
  console.error(
    'Faltam EXPO_PUBLIC_SUPABASE_URL e EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY (.env.local).'
  );
  process.exit(1);
}

function sleep(ms) {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function literal(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function clip(text, max) {
  const value = typeof text === 'string' ? text.trim() : '';
  if (!value) return null;
  return value.length <= max ? value : `${value.slice(0, max - 1).trimEnd()}…`;
}

async function overpass(venue) {
  const query =
    `[out:json][timeout:90];way["highway"~"${HIGHWAYS}"]["name"]` +
    `(around:${RADIUS_M},${venue.latitude},${venue.longitude});out geom;`;
  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      const response = await fetch(OVERPASS, {
        method: 'POST',
        headers: { 'User-Agent': USER_AGENT, 'Content-Type': 'application/x-www-form-urlencoded' },
        body: new URLSearchParams({ data: query }),
      });
      if (!response.ok) {
        await sleep(5000);
        continue;
      }
      return (await response.json()).elements ?? [];
    } catch {
      await sleep(5000);
    }
  }
  return null;
}

const wanted = new Set(process.argv.slice(2));

const venuesResponse = await fetch(
  `${SUPABASE_URL}/rest/v1/venue?select=id,name,latitude,longitude&country=eq.Portugal`,
  { headers: { apikey: SUPABASE_KEY } }
);
const allVenues = await venuesResponse.json();
const fixturesResponse = await fetch(`${SUPABASE_URL}/rest/v1/fixture?select=venue_id`, {
  headers: { apikey: SUPABASE_KEY },
});
const withGames = new Set((await fixturesResponse.json()).map((fixture) => fixture.venue_id));
const venues = allVenues
  .filter((venue) => withGames.has(venue.id) && venue.latitude !== null)
  .filter((venue) => wanted.size === 0 || wanted.has(venue.id))
  .sort((a, b) => a.id.localeCompare(b.id));

const statements = [];
const report = { streets: 0, venues: 0 };

for (const venue of venues) {
  const elements = await overpass(venue);
  if (elements === null) {
    console.error(`${venue.id}: Overpass não respondeu, estádio ignorado`);
    continue;
  }

  const rows = [];
  for (const element of elements) {
    const name = clip(element.tags?.name, 120);
    const geometry = element.geometry ?? [];
    if (!name || geometry.length < MIN_POINTS) continue;
    const points = geometry
      .filter((point) => Number.isFinite(point.lat) && Number.isFinite(point.lon))
      .map((point) => `${point.lon} ${point.lat}`);
    if (points.length < MIN_POINTS) continue;
    rows.push({ osmId: `way/${element.id}`, name, line: `LINESTRING(${points.join(',')})` });
  }

  statements.push(`delete from public.venue_street where venue_id = ${literal(venue.id)};`);
  for (const row of rows) {
    statements.push(
      `insert into public.venue_street (venue_id, osm_id, name, path) values (` +
        `${literal(venue.id)}, ${literal(row.osmId)}, ${literal(row.name)}, ` +
        `extensions.st_setsrid(extensions.st_geomfromtext(${literal(row.line)}), 4326)::extensions.geography) ` +
        `on conflict (venue_id, osm_id) do nothing;`
    );
  }

  report.streets += rows.length;
  report.venues += 1;
  const nomes = new Set(rows.map((row) => row.name));
  console.error(`${venue.id}: ${rows.length} troços, ${nomes.size} ruas com nome`);
}

console.log('-- Generated by scripts/importar-ruas-estadios.mjs. © OpenStreetMap contributors.');
console.log('begin;');
console.log(statements.join('\n'));
console.log('commit;');
console.error(`\n${report.streets} troços em ${report.venues} estádios.`);
