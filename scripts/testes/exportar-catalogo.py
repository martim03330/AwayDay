#!/usr/bin/env python3
"""Exports the public catalogue tables from production into supabase/tests/catalogo.sql, for the SQL tests in CI.

The CI creates an empty Supabase from the migrations and the seed; the seed has no tascos, car parks or streets
(they come from scripts and syncs), and some tests need a few. Only public catalogue data goes in: who suggested a
tasco is left out. Run again when those tables change in a way the tests care about:

    python3 scripts/testes/exportar-catalogo.py
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[2]
DESTINO = RAIZ / 'supabase' / 'tests' / 'catalogo.sql'

# Fewer rows where the tables are big and the tests only need some (a few streets per stadium).
FILTROS = {
    'venue_street': 'where (venue_id, id) in (select venue_id, id from (select venue_id, id, '
    'row_number() over (partition by venue_id order by id) as n from public.venue_street) as r where n <= 5)',
}

# In foreign-key order. Columns listed here are written as null (personal data).
TABELAS = {
    'municipality': [],
    'fixture': [],
    'place': ['suggested_by'],
    'parking_spot': [],
    'venue_parking': [],
    'venue_street': [],
    'restroom': [],
    'toll_rate': [],
}


def consulta(sql: str):
    with tempfile.NamedTemporaryFile('w', suffix='.sql', delete=False) as ficheiro:
        ficheiro.write(sql)
    saida = subprocess.run(
        ['supabase', 'db', 'query', '--linked', '-o', 'json', '-f', ficheiro.name],
        capture_output=True, text=True, cwd=RAIZ, check=True,
    ).stdout
    return json.loads(saida[saida.index('{'):saida.rindex('}') + 1])['rows']


def literal(valor, tipo: str):
    if valor is None:
        return 'null'
    if tipo == 'ARRAY':
        valor = json.dumps(valor)[1:-1] if isinstance(valor, list) else valor
        return "'{" + str(valor).replace("'", "''") + "}'"
    if isinstance(valor, (dict, list)):
        return "'" + json.dumps(valor, ensure_ascii=False).replace("'", "''") + "'"
    if isinstance(valor, bool):
        return 'true' if valor else 'false'
    if isinstance(valor, (int, float)):
        return repr(valor)
    return "'" + str(valor).replace("'", "''") + "'"


def main():
    partes = [
        '-- Generated by scripts/testes/exportar-catalogo.py: public catalogue tables from production, for the SQL',
        '-- tests in CI (never loaded into production). Do not edit by hand.',
        'set session_replication_role = replica;',
    ]
    for tabela, pessoais in TABELAS.items():
        colunas = consulta(
            "select column_name, data_type from information_schema.columns "
            f"where table_schema = 'public' and table_name = '{tabela}' and is_generated = 'NEVER' "
            "and coalesce(identity_generation, '') <> 'ALWAYS' order by ordinal_position"
        )
        nomes = [c['column_name'] for c in colunas]
        tipos = {c['column_name']: c['data_type'] for c in colunas}
        seletor = ', '.join(
            f'{n}::text as {n}' if tipos[n] in ('USER-DEFINED', 'ARRAY') else n for n in nomes
        )
        linhas = consulta(f'select {seletor} from public.{tabela} {FILTROS.get(tabela, "")}')
        print(f'{tabela}: {len(linhas)} linhas', file=sys.stderr)
        if not linhas:
            continue
        valores = []
        for linha in linhas:
            campos = []
            for n in nomes:
                if n in pessoais:
                    campos.append('null')
                elif tipos[n] == 'ARRAY':
                    campos.append(literal(linha[n], 'text'))
                else:
                    campos.append(literal(linha[n], tipos[n]))
            valores.append('(' + ', '.join(campos) + ')')
        for inicio in range(0, len(valores), 500):
            partes.append(
                f'insert into public.{tabela} ({", ".join(nomes)}) values\n  '
                + ',\n  '.join(valores[inicio:inicio + 500])
                + '\non conflict do nothing;'
            )
    partes.append('set session_replication_role = origin;')
    DESTINO.write_text('\n'.join(partes) + '\n', encoding='utf-8')
    print(f'{DESTINO.relative_to(RAIZ)}: {DESTINO.stat().st_size // 1024} KB', file=sys.stderr)


if __name__ == '__main__':
    main()
